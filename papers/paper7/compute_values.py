def external_audit():
    """Static audit of published artefacts and the RF id/dedup check.
    matrix_v2.json (independent recode + new columns, REPORT_v2.md) is authoritative; matrix.json (first coding)
    is used only for the agreement rate. v2 F16 codes: A = untuned tree ensemble present, P = no tree ensemble
    although other baselines exist, ND = no baseline code. No repository contains a tuned tree ensemble."""
    if not (AUDIT / 'matrix_v2.json').exists():
        # public copy: the audit coding is withheld (Section 5.3), so keep the released values of the audit keys
        old = jl(HERE / 'values.json')
        V.update({k: v for k, v in old.items() if k.startswith('P7:ext_')})
        print('external audit folder not present: P7:ext_* copied from the released values.json')
        return
    M2 = jl(AUDIT / 'matrix_v2.json')
    M = M2['papers'] if 'papers' in M2 else {k: v for k, v in M2.items() if not k.startswith('_')}
    put('ext_n', str(len(M)))
    # Review round 3 (minor 19): F4 risk = heavy-tailed counts fed to a network with no NONLINEAR transform
    # (log, power, quantile). Standardising or robust scaling is linear and keeps the heavy tail, so the two
    # repositories coded 'A' only because they standardise (StandardScaler / RobustScaler, see 'scaler') become 'P'.
    M = {k: dict(v) for k, v in M.items()}
    for k in ('P3_Zhang2020', 'P5_Dlamini2021'):
        assert M[k]['F4'] == 'A' and ('StandardScaler' in M[k]['scaler'] or 'RobustScaler' in M[k]['scaler']), k
        M[k]['F4'] = 'P'
    # Repositories whose account name matches an author or the authors' laboratory (5 of 9, Section 5.3).
    OWN = ('P1_Vinayakumar2019', 'P3_Zhang2020', 'P4_Zhang2024', 'P6_Zhang2025', 'P9_Zaccagnino2023')
    own2 = [M[k]['F2'] for k in OWN if M[k]['F2'] not in ('ND', 'NA')]
    assert all(v == 'P' for v in own2)
    put('ext_own_F2_n', str(len(own2)))
    put('ext_own_n', str(len(OWN)))
    for col in ('F1', 'F2', 'prep', 'F3', 'F9', 'F17', 'F4', 'F5', 'F6', 'F14'):
        det = [p[col] for p in M.values() if p[col] not in ('ND', 'NA')]
        put(f'ext_{col}', f"{sum(v == 'P' for v in det)} of {len(det)}")
        put(f'ext_{col}_k', str(sum(v == 'P' for v in det)))
        put(f'ext_{col}_n', str(len(det)))
    put('ext_ttl_ablated', str(sum(p.get('F3_TTL_ablated') == 'yes' for p in M.values())))
    put('ext_F16_untuned', str(sum(p['F16'] == 'A' for p in M.values())))
    put('ext_F16_notree', str(sum(p['F16'] == 'P' for p in M.values())))
    put('ext_F16_nobase', str(sum(p['F16'] == 'ND' for p in M.values())))
    # agreement of the independent recode with the first coding (7 shared columns); F16 convention mapped
    M1 = jl(AUDIT / 'matrix.json')['papers']
    f16map = {'partial': 'A', 'A': None}
    agree = lit = tot = 0
    for k, p1 in M1.items():
        p2 = M[k]
        for col in ('F1', 'F2', 'prep', 'F3', 'F9', 'F16', 'F17'):
            tot += 1
            lit += p1[col] == p2[col]
            if col == 'F16':
                a = p1[col]
                ok = (a == 'partial' and p2[col] == 'A') or (a == 'A' and p2[col] in ('P', 'ND')) or a == p2[col]
            else:
                ok = p1[col] == p2[col]
            agree += ok
    put('ext_agree_literal', f'{lit} of {tot}')
    put('ext_agree_mapped', f'{agree} of {tot}')
    put('ext_hand_checked', '6')   # 3 in REPORT.md (prep: P2, P4, P9) + 3 in REPORT_v2.md (F5 P9, F6 P7, F9 P8)
    put('ext_F4_bn', str(sum(p['F4'] == 'P' and p.get('batchnorm') is True for p in M.values())))
    R = jl(AUDIT / 'scripts/rf_id_dedup_results.json')['results']
    def cell(dedup, keep):
        return [r for r in R if r['dedup'] == dedup and r['keep_id'] == keep]
    put('ext_rf_copy_pct', f"{100 * st.mean(r['test_share_with_copy_in_train'] for r in cell(False, True)):.1f}%")
    for dd, tag in ((False, 'nodedup'), (True, 'dedup')):
        a = {r['seed']: r['macro_f1'] for r in cell(dd, True)}
        b = {r['seed']: r['macro_f1'] for r in cell(dd, False)}
        d = [a[s] - b[s] for s in a]
        put(f'ext_rf_id_{tag}', f'+{min(d):.3f} to +{max(d):.3f}')


def review_rounds():
    """Reviewer-instance outcomes for the corrected Studies 4-6 (review reports on disk; Study 3's single round
    has no report). Source: review_rounds_table.md, Table 1 (per report), built from the reports, STATUS.md,
    response files and commit logs. Study 4's round-1 numbers audit is excluded (superseded by a full rebuild)."""
    import re
    rows = []
    for line in (HERE / 'review_rounds_table.md').read_text(encoding='utf-8').splitlines():
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) >= 10 and c[0] in ('P4', 'P5', 'P6'):
            rows.append(c)
    def num(s):
        m = re.match(r'\s*(\d+)', s)
        return int(m.group(1)) if m else 0
    tot = {k: 0 for k in ('raised', 'fixed', 'partly', 'rejected', 'unknown', 'changed')}
    roles = {}
    nrep = 0
    for c in rows:
        if c[0] == 'P4' and c[1].startswith('r1') and c[2] == 'numbers':
            continue
        nrep += 1
        role = c[2].split()[0]
        vals = dict(raised=num(c[3]), fixed=num(c[4]), partly=num(c[5]), rejected=num(c[6]), unknown=num(c[7]),
                    changed=num(c[9]))
        for k, v in vals.items():
            tot[k] += v
            roles.setdefault(role, {kk: 0 for kk in tot})[k] += v
    put('rev_reports', str(nrep))
    for k, v in tot.items():
        put(f'rev_{k}', str(v))
    known = tot['fixed'] + tot['partly'] + tot['rejected']
    put('rev_fixed_pct_known', f"{100 * (tot['fixed'] + tot['partly']) / known:.0f}%")
    put('rev_rejected_pct_known', f"{100 * tot['rejected'] / known:.0f}%")
    for r, d in roles.items():
        for k, v in d.items():
            put(f'rev_{r}_{k}', str(v))
        put(f'rev_{r}_fixedany', str(d['fixed'] + d['partly']))
    put('rev_fixedany', str(tot['fixed'] + tot['partly']))


def p1_rerun():
    """Identical-configuration XLA reruns (TON seed 0) caused by the .h5 overwrite bug."""
    old = EXP / 'baseline/results_v2_superseded_h5bug/TON_IoT'
    new = EXP / 'baseline/results_v2/TON_IoT'
    diffs = {}
    for cfg in ('cnn_w1', 'mlp_w1'):
        a, b = jl(old / cfg / 'seed0.json'), jl(new / cfg / 'seed0.json')
        diffs[cfg] = abs(a['macro_f1'] - b['macro_f1'])
        ia, ib = a.get('int8') or {}, b.get('int8') or {}
        if 'macro_f1' in ia and 'macro_f1' in ib:
            diffs[cfg + '_int8'] = abs(ia['macro_f1'] - ib['macro_f1'])
    put('p1_rerun_float_max', f"{max(diffs['cnn_w1'], diffs['mlp_w1']):.4f}")
    if 'mlp_w1_int8' in diffs:
        put('p1_rerun_int8_max', f"{max(v for k, v in diffs.items() if 'int8' in k):.4f}")


