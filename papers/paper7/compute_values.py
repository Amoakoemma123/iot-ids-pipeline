def p1_v1():
    """P1 v1: file sizes, latency timing method, CNN/RF scores."""
    m = jl(V1 / 'baseline/results/TON_IoT/metrics.json')
    put('p1v1_cnn_f1', f3(m['cnn']['macro_f1']))
    put('p1v1_rf_f1', f3(m['rf']['macro_f1']))
    put('p1v1_rf_cnn_gap', f3(m['rf']['macro_f1'] - m['cnn']['macro_f1']))
    mod = V1 / 'baseline/results/models'
    # the original model files (forest pickle ~99 MB) are not in the public repository; their byte sizes and
    # SHA-256 are in model_file_sizes.json, written from the files by make_model_manifest() in the working tree
    man = jl(mod / 'model_file_sizes.json') if (mod / 'model_file_sizes.json').exists() else {}
    def size(rel):
        return os.path.getsize(mod / rel) if (mod / rel).exists() else man[rel]['bytes']
    rf_t = size('TON_IoT/model_rf.pkl')
    cnn_t = size('TON_IoT/model_cnn.h5')
    rf_u = size('UNSW_NB15/model_rf.pkl')
    cnn_u = size('UNSW_NB15/model_cnn.h5')
    # KB = 1,024 bytes, as in Paper 1 (P1:*_kb keys) and in the original "350 KB"
    put('p1v1_rf_kb_ton', f'{rf_t / 1024:,.0f}')
    put('p1v1_cnn_kb_ton', f'{cnn_t / 1024:.0f}')
    put('p1v1_size_ratio_ton', f'{rf_t / cnn_t:.0f}')
    put('p1v1_size_ratio_unsw', f'{rf_u / cnn_u:.0f}')
    lat = jl(V1 / 'baseline/results/TON_IoT/latency.json')
    put('p1v1_lat_cnn_ms', f"{lat['cnn']['mean_ms']:.2f}")
    put('p1v1_lat_rf_ms', f"{lat['rf']['mean_ms']:.2f}")
    put('p1v1_lat_runs', f"{lat['cnn']['total_ms'] / lat['cnn']['mean_ms']:.0f}")


