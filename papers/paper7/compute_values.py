"""Paper 7: every number quoted in Manuscript.md.

Two sources:
  1. Final values of Papers 1-6: every key of Revision_v2/PaperX/values.json is copied as "PX:key"
     (P2 is regenerated by its own compute_values.py before this runs; see main()).
  2. Numbers P7 computes itself, mostly from v1 result files (_v1_backup_2026-10-24) and a few
     diagnostics that the per-paper scripts do not report. Keys have the prefix "P7:".
Writes values.json. Placeholders {{PX:key}} / {{P7:key}} are filled by build.py.
"""
import glob
import json
import os
import statistics as st
from pathlib import Path

HERE = Path(__file__).resolve().parent
if HERE.parent.name == 'papers' and (HERE.parents[1] / 'experiments').is_dir():
    # public repository layout: <repo>/papers/paper7, companion papers in <repo>/papers/paper1..6,
    # original (v1) result files in papers/paper7/original_v1/experiments
    PIPE = HERE.parents[1]
    PAPER_DIR = lambda i: HERE.parent / f'paper{i}'          # noqa: E731
    V1 = HERE / 'original_v1' / 'experiments'
else:
    # authors' working tree
    REV = HERE.parent
    ROOT = REV.parent
    PIPE = ROOT / 'Papers pipeline'
    PAPER_DIR = lambda i: REV / f'Paper{i}'                  # noqa: E731
    V1 = ROOT / '_v1_backup_2026-10-24' / 'experiments'
EXP = PIPE / 'experiments'
AUDIT = HERE / 'external_audit'   # not released publicly (anonymous audit); see external_audit() below
V = {}


def put(k, v):
    V['P7:' + k] = v


def jl(p):
    return json.loads(Path(p).read_text(encoding='utf-8'))


def f3(x):
    return f'{x:.3f}'


# ---------------------------------------------------------------- 1. per-paper values
def copy_papers():
    for i in range(1, 7):
        p = PAPER_DIR(i) / 'values.json'
        d = jl(p)
        for k, v in d.items():
            if k == 'tables':
                continue
            if isinstance(v, (str, int, float)):
                V[f'P{i}:{k}'] = str(v)
        # P1 stores some values under "tables"? keep tables out of P7 (P7 quotes scalars only)


