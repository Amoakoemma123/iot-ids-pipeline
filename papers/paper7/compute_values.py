def p3_caps_and_epochs():
    caps = {'results_v2': (40, 20), 'results_v3': (100, 50)}
    for rd, (c0, ci) in caps.items():
        for ds, tag in (('TON_IoT', 'ton'), ('UNSW_NB15', 'unsw'), ('N_BaIoT', 'nb')):
            n = hit = 0
            for p in glob.glob(str(EXP / f'paper3_continual/{rd}/{ds}/main/*.json')):
                d = jl(p)
                joint = d['strategy'] == 'joint'
                for t, stg in enumerate(d['stages']):
                    cap = c0 if (t == 0 or joint) else ci
                    n += 1
                    hit += stg['epochs'] >= cap
            if n:
                put(f'p3_caphit_{rd[-2:]}_{tag}', f'{100 * hit / n:.0f}%')
    ep = []
    for p in glob.glob(str(EXP / 'paper3_continual/results_v2/TON_IoT/main/joint_o0_s*.json')):
        ep += [s['epochs'] for s in jl(p)['stages']]
    put('p3v2_joint_epochs_min', str(min(ep)))
    put('p3v2_joint_epochs_max', str(max(ep)))


